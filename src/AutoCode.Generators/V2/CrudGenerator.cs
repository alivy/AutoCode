                    .Parameter(e.KeyType, "id")
                    .Returns($"Task<{e.Name}?>")
                    .Body(b => b.Return("await _dbSet.FindAsync(id)")));

                // FindAsync
                c.Method("FindAsync", m => m.Public().Async()
                    .Parameter($"Expression<Func<{e.Name}, bool>>", "predicate")
                    .Returns($"Task<List<{e.Name}>>")
                    .Body(b => b.Return("await _dbSet.Where(predicate).ToListAsync()")));

                // GetPagedAsync
                c.Method("GetPagedAsync", m => m.Public().Async()
                    .Parameter("int", "page")
                    .Parameter("int", "pageSize")
                    .Parameter($"Expression<Func<{e.Name}, bool>>?", "filter", "null")
                    .Returns($"Task<(List<{e.Name}> Items, int Total)>")
                    .Body(b =>
                    {
                        b.Var("query", "_dbSet.AsQueryable()");
                        if (e.HasSoftDelete)
                            b.Line("query = query.Where(x => !x.IsDeleted);");
                        b.Line("if (filter != null) query = query.Where(filter);");
                        b.Var("total", "await query.CountAsync()");
                        b.Var("items", "await query.Skip((page - 1) * pageSize).Take(pageSize).ToListAsync()");
                        b.Return("(items, total)");
                    }));

                // AddAsync
                c.Method("AddAsync", m => m.Public().Async()
                    .Parameter(e.Name, "entity")
                    .Returns($"Task<{e.Name}>")
                    .Body(b =>
                    {
                        if (e.HasAudit)
                        {
                            b.Line("entity.CreatedAt = DateTime.UtcNow;");
                        }
                        b.Line("await _dbSet.AddAsync(entity);");
                        b.Line("await _context.SaveChangesAsync();");
                        b.Return("entity");
                    }));

                // UpdateAsync
                c.Method("UpdateAsync", m => m.Public().Async()
                    .Parameter(e.Name, "entity")
                    .Returns($"Task<{e.Name}?>")
                    .Body(b =>
                    {
                        b.Var("existing", "await _dbSet.FindAsync(entity.Id)");
                        b.If("existing == null").Return("null").End();
                        if (e.HasAudit)
                            b.Line("entity.ModifiedAt = DateTime.UtcNow;");
                        b.Line("_context.Entry(existing).CurrentValues.SetValues(entity);");
                        b.Line("await _context.SaveChangesAsync();");
                        b.Return("existing");
                    }));

                // DeleteAsync
                c.Method("DeleteAsync", m => m.Public().Async()
                    .Parameter(e.KeyType, "id")
                    .Returns("Task<bool>")
                    .Body(b =>
                    {
                        b.Var("entity", "await _dbSet.FindAsync(id)");
                        b.If("entity == null").Return("false").End();
                        if (e.HasSoftDelete)
                        {
                            b.Line("entity.IsDeleted = true;");
                            b.Line("entity.DeletedAt = DateTime.UtcNow;");
                        }
                        else
                        {
                            b.Line("_dbSet.Remove(entity);");
                        }
                        b.Line("await _context.SaveChangesAsync();");
                        b.Return("true");
                    }));

                // CountAsync
                c.Method("CountAsync", m => m.Public().Async()
                    .Returns("Task<int>")
                    .Body(b =>
                    {
                        if (e.HasSoftDelete)
                            b.Return("await _dbSet.CountAsync(x => !x.IsDeleted)");
                        else
                            b.Return("await _dbSet.CountAsync()");
                    }));
            });

            return new CrudFile { FileName = $"{e.Name}Repository.g.cs", Content = w.Build() };
        }

