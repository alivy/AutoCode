            w.Interface($"I{e.Name}Repository", c =>
            {
                c.Public();
                c.Doc($"{e.Name} 仓储接口（由 AutoCode CRUD 自动生成）");

                c.Method("GetAllAsync", m => m
                    .Returns($"Task<List<{e.Name}>>")
                    .Doc("获取所有记录"));
                c.Method("GetByIdAsync", m => m
                    .Parameter(e.KeyType, "id")
                    .Returns($"Task<{e.Name}?>")
                    .Doc("根据 ID 获取"));
                c.Method("FindAsync", m => m
                    .Parameter($"Expression<Func<{e.Name}, bool>>", "predicate")
                    .Returns($"Task<List<{e.Name}>>")
                    .Doc("条件查询"));
                c.Method("GetPagedAsync", m => m
                    .Parameter("int", "page")
                    .Parameter("int", "pageSize")
                    .Parameter($"Expression<Func<{e.Name}, bool>>?", "filter", "null")
                    .Returns($"Task<(List<{e.Name}> Items, int Total)>")
                    .Doc("分页查询"));
                c.Method("AddAsync", m => m
                    .Parameter(e.Name, "entity")
                    .Returns($"Task<{e.Name}>")
                    .Doc("新增"));
                c.Method("UpdateAsync", m => m
                    .Parameter(e.Name, "entity")
                    .Returns($"Task<{e.Name}?>")
                    .Doc("更新"));
                c.Method("DeleteAsync", m => m
