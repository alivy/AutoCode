    /// <summary>
    /// CRUD 一键生成器 - 从实体类生成完整 CRUD 栈：
    /// IRepository 接口 + EF Core 实现 + IService 接口 + Service + Controller。
    /// 支持软删除、审计日志、分页查询。
    /// </summary>
    [Generator]
    public class CrudGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var crudSources = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (node, _) => node is ClassDeclarationSyntax cds &&
                        cds.AttributeLists.SelectMany(a => a.Attributes).Any(a =>
                        {
                            var name = a.Name is IdentifierNameSyntax id ? id.Identifier.Text : a.Name.ToString();
                            return name == "AutoCrud" || name == "AutoCrudAttribute";
                        }),
                    transform: static (ctx, ct) => ExtractEntityInfo(ctx, ct))
                .Where(static s => s != null)
                .SelectMany(static (info, _) => GenerateAllFiles(info!));

            context.RegisterSourceOutput(crudSources, static (spc, file) =>
            {
                spc.AddSource(file.FileName, SourceText.From(file.Content, Encoding.UTF8));
            });
        }

        private static EntityInfo? ExtractEntityInfo(GeneratorSyntaxContext ctx, CancellationToken ct)
        {
            if (ctx.Node is not ClassDeclarationSyntax classDecl)
                return null;

            var entitySymbol = ctx.SemanticModel.GetDeclaredSymbol(classDecl, ct) as INamedTypeSymbol;
            if (entitySymbol == null)
                return null;

            var attr = entitySymbol.GetAttributes().FirstOrDefault(a =>
                a.AttributeClass?.Name == "AutoCrudAttribute" || a.AttributeClass?.Name == "AutoCrud");

            // 获取主键
            var keyProp = entitySymbol.GetMembers().OfType<IPropertySymbol>()
                .FirstOrDefault(p => p.Name == "Id");
            var keyType = keyProp?.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat) ?? "int";

            // 获取属性
            var properties = entitySymbol.GetMembers().OfType<IPropertySymbol>()
                .Where(p => p.DeclaredAccessibility == Microsoft.CodeAnalysis.Accessibility.Public)
                .Where(p => !p.IsStatic && !p.IsIndexer)
                .Select(p => new PropInfo
                {
                    Name = p.Name,
                    Type = p.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)
                })
                .ToList();

            // 检测软删除和审计
            var hasSoftDelete = entitySymbol.GetAttributes().Any(a => a.AttributeClass?.Name == "SoftDeleteAttribute");
            var hasAudit = entitySymbol.GetAttributes().Any(a => a.AttributeClass?.Name == "AuditableAttribute");

            // 路由
            var routePrefix = attr?.NamedArguments
                .FirstOrDefault(a => a.Key == "RoutePrefix").Value.Value as string;

            return new EntityInfo
            {
                Name = entitySymbol.Name,
                FullName = entitySymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                Namespace = entitySymbol.ContainingNamespace?.ToDisplayString() ?? "",
                KeyType = keyType,
                Properties = properties,
                HasSoftDelete = hasSoftDelete,
                HasAudit = hasAudit,
                RoutePrefix = routePrefix ?? $"api/{entitySymbol.Name.ToLowerInvariant()}s"
            };
        }

        private static List<CrudFile> GenerateAllFiles(EntityInfo entity)
        {
            var files = new List<CrudFile>();

            files.Add(GenerateIRepository(entity));
            files.Add(GenerateRepository(entity));
            files.Add(GenerateIService(entity));
            files.Add(GenerateService(entity));
            files.Add(GenerateController(entity));

            return files;
        }

