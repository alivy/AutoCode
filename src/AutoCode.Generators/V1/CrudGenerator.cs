            var i = string.IsNullOrEmpty(ns) ? "" : "    ";

            sb.AppendLine($"{i}/// <summary>");
            sb.AppendLine($"{i}/// {entity} CRUD 服务接口（由 AutoCode.Crud 自动生成）");
            sb.AppendLine($"{i}/// </summary>");
            sb.AppendLine($"{i}public interface I{entity}Service");
            sb.AppendLine($"{i}{{");
            sb.AppendLine($"{i}    List<{entityFull}> GetAll();");
            sb.AppendLine($"{i}    {entityFull}? GetById({keyType} id);");
            sb.AppendLine($"{i}    {entityFull} Create({entityFull} entity);");
