    /// <summary>
    /// AutoCrud 生成器 - 一键生成 CRUD Service + Interface + Controller
    /// </summary>
    [Generator]
    public class CrudGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var crudSources = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: (node, _) => node is ClassDeclarationSyntax cds &&
                        cds.AttributeLists.SelectMany(a => a.Attributes).Any(a =>
                        {
                            var name = a.Name is IdentifierNameSyntax id ? id.Identifier.Text : a.Name.ToString();
                            return name == "AutoCrud" || name == "AutoCrudAttribute";
                        }),
                    transform: (ctx, _) => GenerateCrud(ctx))
                .Where(s => s != null)!
                .SelectMany((sources, _) => sources);

            context.RegisterSourceOutput(crudSources, (spc, source) =>
            {
                spc.AddSource(source.FileName, SourceText.From(source.SourceText, Encoding.UTF8));
            });
        }

        private static List<GeneratedSource> GenerateCrud(GeneratorSyntaxContext ctx)
        {
            var result = new List<GeneratedSource>();

            if (ctx.Node is not ClassDeclarationSyntax classDecl)
                return result;

            var entitySymbol = ctx.SemanticModel.GetDeclaredSymbol(classDecl) as INamedTypeSymbol;
            if (entitySymbol == null)
                return result;

            var namespaceName = entitySymbol.ContainingNamespace?.ToDisplayString() ?? "";
            var entityName = entitySymbol.Name;
            var entityFullName = entitySymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            // 获取主键属性
            var keyProp = entitySymbol.GetMembers().OfType<IPropertySymbol>()
                .FirstOrDefault(p => p.Name == "Id");
            var keyType = keyProp?.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) ?? "int";

            // 获取所有公共属性
            var properties = entitySymbol.GetMembers().OfType<IPropertySymbol>()
                .Where(p => p.DeclaredAccessibility == Accessibility.Public)
                .Where(p => !p.IsStatic && !p.IsIndexer)
                .ToList();

            // 1. 生成 IService 接口
            result.Add(new GeneratedSource
            {
                FileName = $"I{entityName}Service.g.cs",
                SourceText = GenerateIService(namespaceName, entityName, entityFullName, keyType)
            });

            // 2. 生成 Service 实现（内存存储）
            result.Add(new GeneratedSource
            {
                FileName = $"{entityName}Service.g.cs",
                SourceText = GenerateService(namespaceName, entityName, entityFullName, keyType, properties)
            });

            // 3. 生成 Controller
            result.Add(new GeneratedSource
            {
                FileName = $"{entityName}sController.g.cs",
                SourceText = GenerateController(namespaceName, entityName, entityFullName, keyType)
            });

            return result;
        }

